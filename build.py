#!/usr/bin/env python3
"""Build the film: one self-contained HTML page (docs/index.html) from scenes.json and src/.

What it does:
  - reads scenes.json (ids, lengths, colours, on-screen text, spoken lines) and counts the film's own facts from it
    (scenes, seconds), which the film shows on screen, so those numbers are counted, never typed;
  - writes audio/voice_script.json for make_audio.py (each scene's start, length and spoken line or cues);
  - inlines the colour tokens, the stylesheet, the icon sprite, the Three.js bundle (MIT, its notice kept) and film.js
    into src/template.html, embeds audio/track.mp3 as a data URI when it exists, and hashes the inline style and scripts
    into a strict Content-Security-Policy.
Order: build.py (voice script) -> make_audio.py (track) -> build.py (page).
Run:   python3 build.py

Author:  Muhammad Akhtar Shamim
Licence: MIT (see LICENSE)
Created: 2026-11-21
"""
import base64
import hashlib
import html
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "src")
OUT = os.path.join(HERE, "docs", "index.html")
TRACK = os.path.join(HERE, "audio", "track.mp3")
VOICE_SCRIPT = os.path.join(HERE, "audio", "voice_script.json")
CAPTION_HOLD = 0.25                   # seconds a subtitle stays after its phrase ends
DEFAULT_LANGUAGE = "en"             # used when scenes.json names no language
AUDIO_NOTE = "The voiceover is a synthesised voice (Kokoro-82M) and the music was generated by code. Keys: space plays and pauses, arrows jump between scenes, c shows or hides captions, m mutes, f goes fullscreen."
AUDIO_FACTS = os.path.join(HERE, "audio", "audio_facts.json")
SUBTITLES = os.path.join(HERE, "assets", "trailer.srt")
# nothing is loaded from anywhere: the page is one file and makes no request to any other site
CSP = ("default-src 'none'; script-src {scripts}; style-src {style}; "
       "img-src data:;{media} base-uri 'none'; form-action 'none'; connect-src 'none'; object-src 'none'")


def read(*parts: str) -> str:
    """Read a UTF-8 text file under this folder."""
    with open(os.path.join(HERE, *parts), encoding="utf-8") as f:
        return f.read()


def sha256_src(text: str) -> str:
    """CSP source expression for an inline block: 'sha256-<base64>'."""
    return "'sha256-" + base64.b64encode(hashlib.sha256(text.encode("utf-8")).digest()).decode() + "'"


def voice_script(scenes: list) -> dict:
    """Each scene's start, length and spoken line, for make_audio.py."""
    at, out = 0, []
    for s in scenes:
        out.append({"id": s["id"], "start": at, "dur": s["dur"], "text": s["say"], **({"cues": s["cues"]} if s.get("cues") else {})})
        at += s["dur"]
    return {"total": at, "scenes": out}


def spoken_clips(script_sha: str) -> list:
    """The spoken phrases (start, seconds, text) from audio_facts.json, or [] when that sound was made for another script."""
    if not os.path.exists(AUDIO_FACTS):
        return []
    with open(AUDIO_FACTS, encoding="utf-8") as f:
        facts = json.load(f)
    return facts["clips"] if facts.get("script_sha256") == script_sha else []


def page_language(code: str) -> str:
    """Turn a scenes.json language code ("en", "pt-br") into the tag HTML expects ("en", "pt-BR")."""
    base, _, region = code.partition("-")
    return base.lower() + ("-" + region.upper() if region else "")


def srt_time(seconds: float) -> str:
    """Seconds as an SRT timestamp, HH:MM:SS,mmm."""
    ms = round(seconds * 1000)
    return f"{ms // 3600000:02d}:{ms // 60000 % 60:02d}:{ms // 1000 % 60:02d},{ms % 1000:03d}"


def write_subtitles(clips: list) -> None:
    """Write the spoken phrases as a subtitle file (assets/trailer.srt) to upload beside the video."""
    os.makedirs(os.path.dirname(SUBTITLES), exist_ok=True)
    blocks = [f"{n}\n{srt_time(c['start'])} --> {srt_time(c['start'] + c['seconds'] + CAPTION_HOLD)}\n{c['text']}\n" for n, c in enumerate(clips, 1)]
    with open(SUBTITLES, "w", encoding="utf-8") as f:
        f.write("\n".join(blocks))


def main() -> int:
    """Count the facts, write the voice script, fill the template, hash the inline code, write the page."""
    subprocess.run(["node", "--check", os.path.join(SRC, "film.js")], check=True)
    cfg = json.loads(read("scenes.json"))
    scenes = [{k: s[k] for k in ("id", "dur", "colour", "deep", "kicker", "title", "line", "warp") if k in s} for s in cfg["scenes"]]
    seconds = sum(s["dur"] for s in scenes)
    facts = {"scenes": len(scenes), "seconds": seconds, "duration": f"{seconds // 60}:{seconds % 60:02d}"}
    os.makedirs(os.path.dirname(VOICE_SCRIPT), exist_ok=True)
    script_text = json.dumps(voice_script(cfg["scenes"]), indent=1)
    with open(VOICE_SCRIPT, "w", encoding="utf-8") as f:
        f.write(script_text)
    # the track is embedded only when it was made from exactly this script; an older one would put words on the wrong pictures
    spoken = spoken_clips(hashlib.sha256(script_text.encode("utf-8")).hexdigest())
    captions = [{"t": c["start"], "d": c["seconds"], "text": c["text"]} for c in spoken]
    audio = ""
    if os.path.exists(TRACK) and not spoken:
        print("the sound in audio/ was made for an earlier script: not embedded. Run make_audio.py, then build.py again.")
    if os.path.exists(TRACK) and spoken:
        write_subtitles(spoken)
        with open(TRACK, "rb") as f:
            audio = f'<audio id="track" preload="auto" src="data:audio/mpeg;base64,{base64.b64encode(f.read()).decode("ascii")}"></audio>'
    lang = page_language(cfg.get("language", DEFAULT_LANGUAGE))
    page = read("src", "template.html")
    style = page.split("<style>")[1].split("</style>")[0]
    filled = style.replace("[[TOKENS_CSS]]", read("src", "tokens.css").strip()).replace("[[FILM_CSS]]", read("src", "film.css").strip())
    vendor, script = read("vendor", "three.min.js").strip(), read("src", "film.js").strip()
    csp = CSP.format(scripts=sha256_src(vendor) + " " + sha256_src(script), style=sha256_src(filled), media=" media-src data:;" if audio else "")
    data = json.dumps({"lang": lang, "author": cfg.get("author", ""), "scenes": scenes, "facts": facts, "captions": captions, "text": {}}, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c")
    transcript = "\n".join(f'      <li>{html.escape(s["say"])}</li>' for s in cfg["scenes"])
    chapters = "\n".join(f'    <li><span class="k">{html.escape(s["kicker"])}</span><br>{html.escape(s["title"])} {html.escape(s["line"])}</li>' for s in scenes)
    page = page.replace(style, filled)
    for key, value in {"[[CSP]]": csp, "[[ICONS]]": read("src", "icons.svg").strip(), "[[DATA]]": data, "[[VENDOR_JS]]": vendor, "[[FILM_JS]]": script,
                       "[[LANG]]": lang, "[[BRAND]]": html.escape(cfg["brand"]), "[[NOTICE]]": html.escape(cfg["notice"]), "[[AUDIO_NOTE]]": AUDIO_NOTE if audio else "",
                       "[[AUDIO]]": audio, "[[BODY_CLASS]]": "" if audio else "no-track", "[[CHAPTERS]]": chapters, "[[TRANSCRIPT]]": transcript}.items():
        page = page.replace(key, value)
    for key, value in facts.items():
        page = page.replace(f"[[F:{key}]]", str(value))
    left = re.findall(r"\[\[[A-Z_:a-z]+\]\]", page)
    if left:
        raise SystemExit(f"unresolved placeholders: {sorted(set(left))}")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(page)
    print(f"built {os.path.relpath(OUT, HERE)}  {os.path.getsize(OUT) / 1024:.0f} KB  {facts['scenes']} scenes  {seconds} s  audio {'embedded' if audio else 'none yet'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
